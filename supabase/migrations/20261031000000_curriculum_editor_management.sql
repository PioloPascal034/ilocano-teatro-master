-- Curriculum editor authorization and curriculum write access.
-- Apply after ilocano_teatro_master_supabase_setup.sql has completed.
-- This migration is additive: it does not rewrite curriculum, progress, or quiz rows.
-- Do not apply with a Flutter client or a service-role credential.

begin;

-- Only project/database administrators manage this table through the Supabase
-- SQL Editor. No authenticated-user RLS policies or table grants are provided.
create table if not exists public.curriculum_editors (
  editor_id uuid primary key
    references public.profiles(id) on delete cascade,
  granted_at timestamptz not null default now()
);

alter table public.curriculum_editors enable row level security;

revoke all on table public.curriculum_editors
  from public, anon, authenticated;
-- service_role is the trusted, server-only administrative role. Preserve its
-- ability to manage editor assignments; never ship its key in Flutter/web.
grant select, insert, update, delete on table public.curriculum_editors
  to service_role;

create or replace function public.is_curriculum_editor()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.curriculum_editors as ce
    join public.profiles as p on p.id = ce.editor_id
    where ce.editor_id = (select auth.uid())
      and p.role = 'teacher'
  );
$$;

-- The function owner must be able to inspect profiles and curriculum_editors
-- without invoking their caller-facing RLS policies. In Supabase SQL Editor,
-- postgres is the trusted migration owner.
alter function public.is_curriculum_editor() owner to postgres;
revoke all on function public.is_curriculum_editor() from public, anon;
grant execute on function public.is_curriculum_editor()
  to authenticated, service_role;

-- Preserve the installed student SELECT behavior. Explicitly grant SELECT to
-- authenticated users in case this migration is run on a compatible schema
-- where the base grants were applied separately.
grant select on public.learning_modules, public.lessons to authenticated;

-- Remove any broad client write grants before granting only the content fields
-- required by the editor. No DELETE privilege is granted.
revoke insert, update, delete on public.learning_modules
  from public, anon, authenticated;
revoke insert, update, delete on public.lessons
  from public, anon, authenticated;

-- Modules: the UUID remains generated by the database. Editors can create and
-- update title, description, ordering, and publication state.
grant insert (title, description, display_order, is_published)
  on public.learning_modules to authenticated;
grant update (title, description, display_order, is_published)
  on public.learning_modules to authenticated;

-- Lessons: module_id is insert-only; moving/reassigning a lesson to a different
-- module is deliberately outside this editor's permissions.
grant insert (module_id, title, objectives, content, lesson_order, is_published)
  on public.lessons to authenticated;
grant update (title, objectives, content, lesson_order, is_published)
  on public.lessons to authenticated;

-- Existing modules_read allows authenticated users to see only published
-- modules. Existing lessons_read requires both a published lesson and a
-- published parent module. Leave both policies intact; PostgreSQL's default
-- permissive policy composition adds unpublished visibility only for editors.
drop policy if exists modules_curriculum_editor_read
  on public.learning_modules;
create policy modules_curriculum_editor_read
  on public.learning_modules
  for select to authenticated
  using ((select public.is_curriculum_editor()));

drop policy if exists modules_curriculum_editor_insert
  on public.learning_modules;
create policy modules_curriculum_editor_insert
  on public.learning_modules
  for insert to authenticated
  with check ((select public.is_curriculum_editor()));

drop policy if exists modules_curriculum_editor_update
  on public.learning_modules;
create policy modules_curriculum_editor_update
  on public.learning_modules
  for update to authenticated
  using ((select public.is_curriculum_editor()))
  with check ((select public.is_curriculum_editor()));

drop policy if exists lessons_curriculum_editor_read
  on public.lessons;
create policy lessons_curriculum_editor_read
  on public.lessons
  for select to authenticated
  using ((select public.is_curriculum_editor()));

drop policy if exists lessons_curriculum_editor_insert
  on public.lessons;
create policy lessons_curriculum_editor_insert
  on public.lessons
  for insert to authenticated
  with check ((select public.is_curriculum_editor()));

drop policy if exists lessons_curriculum_editor_update
  on public.lessons;
create policy lessons_curriculum_editor_update
  on public.lessons
  for update to authenticated
  using ((select public.is_curriculum_editor()))
  with check ((select public.is_curriculum_editor()));

-- Reorder an entire module's lesson list atomically. The unique constraint on
-- (module_id, lesson_order) makes direct swaps unsafe, so rows first move to a
-- temporary range below the current minimum, then to positions 1..N. Locking
-- the table briefly prevents concurrent lesson inserts from invalidating the
-- exact-list check during this transaction.
create or replace function public.reorder_module_lessons(
  p_module_id uuid,
  p_lesson_ids uuid[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  lesson_count integer;
  distinct_id_count integer;
  min_order integer;
  temp_base bigint;
begin
  if not (select public.is_curriculum_editor()) then
    raise exception 'Curriculum editor permission required'
      using errcode = '42501';
  end if;

  if p_module_id is null or p_lesson_ids is null then
    raise exception 'A module and complete lesson order are required'
      using errcode = '22004';
  end if;

  lock table public.lessons in share row exclusive mode;

  if not exists (
    select 1 from public.learning_modules as m
    where m.module_id = p_module_id
  ) then
    raise exception 'Learning module not found' using errcode = 'P0002';
  end if;

  select count(*)::integer, coalesce(min(l.lesson_order), 0)
    into lesson_count, min_order
  from public.lessons as l
  where l.module_id = p_module_id;

  if cardinality(p_lesson_ids) <> lesson_count then
    raise exception 'Provide every lesson in the module exactly once'
      using errcode = '22023';
  end if;

  select count(distinct requested.lesson_id)::integer
    into distinct_id_count
  from unnest(p_lesson_ids) as requested(lesson_id);

  if distinct_id_count <> lesson_count then
    raise exception 'Lesson identifiers must be unique and non-null'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from unnest(p_lesson_ids) as requested(lesson_id)
    left join public.lessons as l
      on l.lesson_id = requested.lesson_id
     and l.module_id = p_module_id
    where l.lesson_id is null
  ) then
    raise exception 'Every lesson must belong to the requested module'
      using errcode = '22023';
  end if;

  if lesson_count = 0 then
    return;
  end if;

  temp_base := min_order::bigint - lesson_count::bigint;
  if temp_base < -2147483648 then
    raise exception 'Lesson ordering range is exhausted; no order was changed'
      using errcode = '22003';
  end if;

  update public.lessons as l
  set lesson_order = (temp_base + requested.ordinality - 1)::integer
  from unnest(p_lesson_ids) with ordinality
    as requested(lesson_id, ordinality)
  where l.lesson_id = requested.lesson_id
    and l.module_id = p_module_id;

  update public.lessons as l
  set lesson_order = requested.ordinality::integer
  from unnest(p_lesson_ids) with ordinality
    as requested(lesson_id, ordinality)
  where l.lesson_id = requested.lesson_id
    and l.module_id = p_module_id;
end;
$$;

alter function public.reorder_module_lessons(uuid, uuid[]) owner to postgres;
revoke all on function public.reorder_module_lessons(uuid, uuid[])
  from public, anon;
grant execute on function public.reorder_module_lessons(uuid, uuid[])
  to authenticated, service_role;

commit;

